#!/usr/bin/env node
// The Keel isolated reviewer as a Codex subagent. A Codex plugin cannot ship agents, so the
// project gets .codex/agents/keel-reviewer.toml, generated from agents/reviewer.md (the single source).
// Usage, from the project root: codex-reviewer.mjs install [--force] | check
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const AGENT_NAME = 'keel-reviewer';
const AGENT_FILE = join('.codex', 'agents', `${AGENT_NAME}.toml`);
const SOURCE = fileURLToPath(new URL('../agents/reviewer.md', import.meta.url));

// TOML basic strings: escaping \ and " is enough for the text of reviewer.md (no control characters but newline).
const escape = (text) => text.replace(/[\\"]/g, (char) => `\\${char}`);

// Codex agent role file: name, description from the frontmatter, the body as developer_instructions.
export function reviewerToml(markdown) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/.exec(markdown);
  if (!match) throw new Error('agents/reviewer.md has no frontmatter');
  const description = /^description: (.*)$/m.exec(match[1])?.[1];
  if (!description) throw new Error('agents/reviewer.md has no description in the frontmatter');
  return [
    '# Generated by Keel from agents/reviewer.md. Do not edit: run the Keel setup again.',
    `name = "${AGENT_NAME}"`,
    `description = "${escape(description)}"`,
    `developer_instructions = """\n${escape(match[2])}"""`,
    '',
  ].join('\n');
}

// missing | outdated | current, comparing the project file with the generated text.
function agentStatus(current, expected) {
  if (current === null) return 'missing';
  return current === expected ? 'current' : 'outdated';
}

// Shell commands the reviewer may run: reading only. Anything else, an unquoted redirection or parenthesis,
// a background & or a command substitution blocks; quotes are honored so a pattern can hold | or >.
const READERS = new Set(['cat', 'grep', 'ls', 'head', 'tail', 'wc', 'cd', 'pwd']);
const FIND_WRITERS = new Set(['-delete', '-exec', '-execdir', '-ok', '-okdir', '-fprint', '-fprint0', '-fprintf', '-fls']);
const GIT_READERS = new Set(['diff', 'log', 'show', 'status']);
const SED_PRINT = /^((\d+|\$)(,(\d+|\$))?|\/[^/]*\/)p$/;

// Splits a command into segments (separated by &&, ||, ;, | or a newline) of words; null if it cannot be read safely.
function segments(command) {
  const result = [[]];
  let word = null;
  let quote = null;
  const endWord = () => { if (word !== null) result.at(-1).push(word); word = null; };
  for (let i = 0; i < command.length; i += 1) {
    const char = command[i];
    if (quote === "'") {
      if (char === "'") quote = null; else word += char;
      continue;
    }
    if (char === '`' || (char === '$' && command[i + 1] === '(')) return null;
    if (quote === '"') {
      if (char === '"') quote = null;
      else if (char === '\\' && i + 1 < command.length) word += command[(i += 1)];
      else word += char;
      continue;
    }
    if (char === "'" || char === '"') { quote = char; word ??= ''; continue; }
    if (char === '\\' && i + 1 < command.length) { word = (word ?? '') + command[(i += 1)]; continue; }
    // Redirection, background, and ( which bash and zsh use for <(cmd), =(cmd) and glob qualifiers that run code.
    if (char === '>' || char === '(' || char === ')' || (char === '&' && command[i + 1] !== '&')) return null;
    if (/\s/.test(char) && char !== '\n') { endWord(); continue; }
    if (char === '\n' || char === ';' || char === '|' || char === '&') {
      endWord();
      if ((char === '|' || char === '&') && command[i + 1] === char) i += 1;
      result.push([]);
      continue;
    }
    word = (word ?? '') + char;
  }
  if (quote) return null;
  endWord();
  return result;
}

function isReader([program, ...args]) {
  if (READERS.has(program)) return true;
  if (program === 'rg') return !args.some((arg) => arg.startsWith('--pre'));
  if (program === 'find') return !args.some((arg) => FIND_WRITERS.has(arg));
  if (program === 'git') return GIT_READERS.has(args[0]) && !args.some((arg) => arg.startsWith('--output'));
  if (program === 'sed') {
    const options = args.filter((arg) => arg.startsWith('-'));
    const scripts = args.filter((arg) => !arg.startsWith('-'));
    return options.includes('-n') && options.every((arg) => arg === '-n') && SED_PRINT.test(scripts[0] ?? '');
  }
  return false;
}

export function isReadOnlyCommand(command) {
  const parts = segments(String(command ?? ''));
  return Boolean(parts) && parts.every((words) => words.length > 0 && isReader(words));
}

function main([command, ...flags]) {
  if (command !== 'check' && command !== 'install') {
    console.error('usage: codex-reviewer.mjs install [--force] | check');
    process.exit(2);
  }
  const expected = reviewerToml(readFileSync(SOURCE, 'utf8'));
  const path = join(process.cwd(), AGENT_FILE);
  const status = agentStatus(existsSync(path) ? readFileSync(path, 'utf8') : null, expected);
  if (command === 'check') {
    if (status === 'current') return console.log(`${AGENT_FILE}: current`);
    console.error(`${AGENT_FILE}: ${status}; run the Keel setup step for the Codex reviewer`);
    process.exit(1);
  }
  if (status === 'current') return console.log(`${AGENT_FILE}: already current`);
  if (status === 'outdated' && !flags.includes('--force')) {
    console.error(`${AGENT_FILE} differs from the one generated from agents/reviewer.md; nothing written. Run install --force to overwrite it`);
    process.exit(1);
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, expected);
  console.log(`${AGENT_FILE}: written`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
